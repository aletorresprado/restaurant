const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');

module.exports = async ({ api, db, fixture, endpoint, adminToken, staffToken, customerToken, customerId }) => {
  const summary = () => api('GET', 'loyalty/me', undefined, customerToken);
  const adminRoot = `admin/users/${customerId}/loyalty`;
  const adjust = (body, token = adminToken) => api('POST', `${adminRoot}/adjustments`, body, token);
  assert.equal((await api('GET', 'loyalty/me')).status, 401);
  assert.equal((await api('GET', adminRoot, undefined, customerToken)).status, 403);
  const adjustment = { operationId: randomUUID(), points: 5, reason: 'Prueba de ajuste auditado' };
  assert.equal((await adjust(adjustment, staffToken)).status, 403);
  assert.equal((await adjust(adjustment, customerToken)).status, 403);
  assert.equal((await adjust({ ...adjustment, points: 0 })).status, 400);
  assert.equal((await adjust({ ...adjustment, reason: '' })).status, 400);
  assert.equal((await adjust({ ...adjustment, userId: customerId })).status, 400);
  const before = (await summary()).body.balance;
  const duplicates = await Promise.all([adjust(adjustment), adjust(adjustment)]);
  assert.deepEqual(duplicates.map(r => r.status), [200, 200]);
  assert.equal(duplicates[0].body.id, duplicates[1].body.id);
  assert.equal((await summary()).body.balance, before + 5);
  assert.equal((await adjust({ ...adjustment, points: 6 })).status, 409);
  const parallel = await Promise.all([adjust({ ...adjustment, operationId: randomUUID(), points: 2 }), adjust({ ...adjustment, operationId: randomUUID(), points: 3 })]);
  assert.deepEqual(parallel.map(r => r.status), [200, 200]);
  assert.equal((await summary()).body.balance, before + 10);
  const clear = await adjust({ ...adjustment, operationId: randomUUID(), points: -10000 });
  assert.equal(clear.status, 200);
  assert.equal(clear.body.points, -(before + 10));
  assert.deepEqual((await summary()).body, { balance: 0, tier: 'WHITE' });
  const absent = await fixture(180);
  assert.equal((await api('POST', endpoint(absent.id), { outcome: 'NO_SHOW' }, staffToken)).status, 200);
  const zeroPenalty = await db.loyaltyMovement.findUniqueOrThrow({ where: { sourceKey: `attendance:${absent.id}` } });
  assert.equal(zeroPenalty.requestedPoints, -3);
  assert.equal(zeroPenalty.points, 0);
  assert.equal(zeroPenalty.balanceAfter, 0);
  const attended = await fixture(180);
  assert.equal((await api('POST', endpoint(attended.id), { outcome: 'ATTENDED' }, staffToken)).status, 200);
  const survey = `loyalty/reservations/${attended.id}/survey`;
  assert.equal((await api('GET', survey, undefined, customerToken)).body.eligible, true);
  assert.equal((await api('GET', survey, undefined, staffToken)).status, 404);
  assert.equal((await api('POST', survey, { rating: 5 }, staffToken)).status, 403);
  assert.equal((await api('POST', survey, { rating: 0 }, customerToken)).status, 400);
  const replies = await Promise.all([api('POST', survey, { rating: 5 }, customerToken), api('POST', survey, { rating: 5 }, customerToken)]);
  assert.deepEqual(replies.map(r => r.status), [200, 200]);
  assert.equal(replies[0].body.id, replies[1].body.id);
  assert.equal((await api('POST', survey, { rating: 4 }, customerToken)).status, 409);
  assert.equal((await api('GET', survey, undefined, customerToken)).body.submitted, true);
  assert.deepEqual((await summary()).body, { balance: 3, tier: 'WHITE' });
  assert.equal((await api('POST', `loyalty/reservations/${absent.id}/survey`, { rating: 5 }, customerToken)).status, 409);
  assert.equal((await api('POST', `loyalty/reservations/${randomUUID()}/survey`, { rating: 5 }, customerToken)).status, 404);
  const upcoming = await fixture(60);
  await api('POST', endpoint(upcoming.id), { outcome: 'ATTENDED' }, staffToken);
  assert.equal((await api('POST', `loyalty/reservations/${upcoming.id}/survey`, { rating: 5 }, customerToken)).status, 409);
  const bump = await adjust({ ...adjustment, operationId: randomUUID(), points: 27 });
  assert.equal(bump.status, 200);
  assert.deepEqual((await summary()).body, { balance: 31, tier: 'PLATINUM' });
  const history = await api('GET', 'loyalty/me/movements?page=1&limit=2', undefined, customerToken);
  assert.equal(history.status, 200);
  assert.equal(history.body.data.length, 2);
  assert.ok(history.body.data.every(m => m.userId === customerId));
  assert.equal((await api('GET', `${adminRoot}/movements`, undefined, staffToken)).status, 403);
  assert.equal((await api('GET', `${adminRoot}/movements`, undefined, adminToken)).status, 200);
  const historical = await fixture(180, undefined, 'ATTENDED');
  const balanceBeforeReplay = (await summary()).body.balance;
  assert.equal((await api('POST', endpoint(historical.id), { outcome: 'ATTENDED' }, staffToken)).status, 200);
  assert.equal((await summary()).body.balance, balanceBeforeReplay);
  assert.equal(await db.loyaltyMovement.count({ where: { sourceKey: `attendance:${historical.id}` } }), 0);
  console.log('OK: puntos atómicos, saldo mínimo, niveles, ajustes auditados, encuestas, permisos e idempotencia concurrente.');
};

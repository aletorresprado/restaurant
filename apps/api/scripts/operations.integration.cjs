const assert = require('node:assert/strict');

module.exports = async function operationsIntegration({ api, db, branchId, otherBranchId, adminToken, staffToken }) {
  const root = `staff/branches/${branchId}`;
  const tableInput = { tableNumber: 'A-1', capacity: 4 };
  assert.equal((await api('POST', `${root}/tables`, tableInput)).status, 401);
  assert.equal((await api('POST', `staff/branches/${otherBranchId}/tables`, tableInput, staffToken)).status, 403);
  assert.equal((await api('POST', `${root}/tables`, { ...tableInput, capacity: 0 }, adminToken)).status, 400);
  const table = await api('POST', `${root}/tables`, tableInput, staffToken);
  assert.equal(table.status, 201);
  const tableId = table.body.id;
  assert.equal(table.body.tableStatus, 'ACTIVE');
  assert.equal((await api('POST', `${root}/tables`, tableInput, adminToken)).status, 409);
  assert.equal((await api('POST', `staff/branches/${otherBranchId}/tables`, tableInput, adminToken)).status, 201);
  assert.equal((await api('PATCH', `${root}/tables/${tableId}`, { tableNumber: 'A-2' }, adminToken)).status, 400);
  assert.equal((await api('PATCH', `${root}/tables/${tableId}`, {}, adminToken)).status, 400);
  assert.equal((await api('PATCH', `staff/branches/${otherBranchId}/tables/${tableId}`, { capacity: 8 }, adminToken)).status, 404);
  assert.equal((await api('PATCH', `${root}/tables/${tableId}`, { capacity: 6, tableStatus: 'OUT_OF_SERVICE' }, staffToken)).status, 200);
  assert.equal((await api('PATCH', `${root}/tables/${tableId}`, { tableStatus: 'ACTIVE' }, staffToken)).status, 200);
  assert.equal((await api('GET', `${root}/tables`, undefined, staffToken)).body.data[0].capacity, 6);
  const blocks = `${root}/tables/${tableId}/blocks`;
  const blockData = { startAt: '2026-11-02T20:00:00-03:00', endAt: '2026-11-02T22:00:00-03:00', reason: 'Mantenimiento' };
  assert.equal((await api('POST', blocks, { ...blockData, endAt: blockData.startAt }, staffToken)).status, 400);
  assert.equal((await api('POST', blocks, { ...blockData, startAt: '2026-11-02T20:00:00' }, staffToken)).status, 400);
  const competing = await Promise.all([api('POST', blocks, blockData, staffToken), api('POST', blocks, blockData, staffToken)]);
  assert.deepEqual(competing.map(r => r.status).sort(), [201, 409]);
  const block = competing.find(r => r.status === 201);
  assert.equal(block.body.startAt, '2026-11-02T23:00:00.000Z');
  assert.equal((await api('POST', blocks, { ...blockData, startAt: blockData.endAt, endAt: '2026-11-02T23:00:00-03:00' }, staffToken)).status, 201);
  assert.equal((await api('GET', blocks, undefined, staffToken)).body.meta.total, 2);
  assert.equal((await api('DELETE', `${blocks}/${block.body.id}`, undefined, staffToken)).status, 200);

  const schedulePath = `${root}/schedules`;
  const mondayData = { dayOfWeek: 1, openingTime: '22:00', closingTime: '02:00' };
  const monday = await api('POST', schedulePath, mondayData, staffToken);
  assert.equal(monday.status, 201);
  assert.equal((await api('POST', schedulePath, mondayData, staffToken)).status, 409);
  assert.equal((await api('POST', schedulePath, { ...mondayData, dayOfWeek: 8 }, staffToken)).status, 400);
  assert.equal((await api('POST', schedulePath, { ...mondayData, openingTime: '25:00' }, staffToken)).status, 400);
  assert.equal((await api('POST', schedulePath, { ...mondayData, dayOfWeek: 2, openingTime: '01:00', closingTime: '04:00' }, staffToken)).status, 409);
  const tuesday = await api('POST', schedulePath, { ...mondayData, dayOfWeek: 2, openingTime: '02:00', closingTime: '04:00' }, staffToken);
  assert.equal(tuesday.status, 201);
  assert.equal((await api('PATCH', `${schedulePath}/${tuesday.body.id}`, { openingTime: '04:00' }, staffToken)).status, 400);
  assert.equal((await api('PATCH', `${schedulePath}/${tuesday.body.id}`, { openingTime: '01:00' }, staffToken)).status, 409);
  assert.equal((await db.branchSchedule.findUnique({ where: { id: tuesday.body.id } })).openingTime, '02:00');
  assert.equal((await api('PATCH', `staff/branches/${otherBranchId}/schedules/${monday.body.id}`, { isActive: false }, adminToken)).status, 404);
  const hoursPath = `branches/${branchId}/hours?date=2026-11-02`;
  const hours = await api('GET', hoursPath);
  assert.equal(hours.status, 200);
  assert.equal(hours.body.source, 'WEEKLY');
  assert.equal(hours.body.window.startAt, '2026-11-03T01:00:00.000Z');
  assert.equal(hours.body.window.endAt, '2026-11-03T05:00:00.000Z');
  assert.equal((await api('GET', `branches/${branchId}/hours?date=2026-02-30`)).status, 400);
  assert.equal((await api('GET', `branches/${branchId}/hours?date=2026-11-04`)).body.isClosed, true);
  const exceptionsPath = `${root}/schedule-exceptions`;
  assert.equal((await api('POST', exceptionsPath, { date: '2026-11-03', openingTime: '01:00', closingTime: '03:00' }, staffToken)).status, 409);
  const closed = await api('POST', exceptionsPath, { date: '2026-11-02', isClosed: true, reason: 'Feriado' }, staffToken);
  assert.equal(closed.status, 201);
  assert.equal((await api('GET', hoursPath)).body.isClosed, true);
  assert.equal((await api('GET', hoursPath)).body.window, null);
  assert.equal((await api('POST', exceptionsPath, { date: '2026-11-02', isClosed: true }, staffToken)).status, 409);
  assert.equal((await api('PATCH', `${exceptionsPath}/${closed.body.id}`, { isClosed: false }, staffToken)).status, 400);
  assert.equal((await api('PATCH', `${exceptionsPath}/${closed.body.id}`, { isClosed: false, openingTime: '20:00', closingTime: '23:00' }, staffToken)).status, 200);
  assert.equal((await api('GET', hoursPath)).body.source, 'EXCEPTION');
  assert.equal((await api('GET', exceptionsPath, undefined, staffToken)).body.meta.total, 1);
  const nextException = await api('POST', exceptionsPath, { date: '2026-11-03', openingTime: '00:00', closingTime: '01:00' }, staffToken);
  assert.equal(nextException.status, 201);
  assert.equal((await api('DELETE', `${exceptionsPath}/${closed.body.id}`, undefined, staffToken)).status, 409);
  assert.equal((await api('GET', hoursPath)).body.source, 'EXCEPTION');
  assert.equal((await api('DELETE', `${exceptionsPath}/${nextException.body.id}`, undefined, staffToken)).status, 200);
  assert.equal((await api('DELETE', `${exceptionsPath}/${closed.body.id}`, undefined, staffToken)).status, 200);
  assert.equal((await api('GET', hoursPath)).body.source, 'WEEKLY');
  assert.equal((await api('DELETE', `${schedulePath}/${tuesday.body.id}`, undefined, staffToken)).status, 200);
  assert.equal((await api('PATCH', `${schedulePath}/${monday.body.id}`, { isActive: false }, staffToken)).status, 200);
  assert.equal((await api('GET', hoursPath)).body.isClosed, true);
  const concurrentSchedules = await Promise.all([
    api('POST', schedulePath, { dayOfWeek: 3, openingTime: '22:00', closingTime: '02:00' }, staffToken),
    api('POST', schedulePath, { dayOfWeek: 4, openingTime: '01:00', closingTime: '03:00' }, staffToken),
  ]);
  assert.deepEqual(concurrentSchedules.map(r => r.status).sort(), [201, 409]);
  console.log('OK: mesas, estados, pertenencia, horarios nocturnos, excepciones, rollback y bloqueos concurrentes.');
};

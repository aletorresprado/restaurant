$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$credentialPath = Join-Path $projectRoot '.env.postgres.local'
$apiEnvPath = Join-Path $projectRoot 'apps/api/.env'
$psqlPath = 'C:\Program Files\PostgreSQL\16\bin\psql.exe'
$utf8 = New-Object System.Text.UTF8Encoding($false)

if (!(Test-Path -LiteralPath $psqlPath)) { throw 'PostgreSQL 16 no está instalado en la ubicación esperada.' }
if (!(Test-Path -LiteralPath $credentialPath)) { throw 'Falta .env.postgres.local con las credenciales locales de instalación.' }
$credentials = Get-Content -Raw -LiteralPath $credentialPath | ConvertFrom-StringData
if (!$credentials.APP_PASSWORD) {
    $bytes = New-Object byte[] 32
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $credentials.APP_PASSWORD = [BitConverter]::ToString($bytes).Replace('-', '')
    [System.IO.File]::AppendAllText($credentialPath, "APP_PASSWORD=$($credentials.APP_PASSWORD)`n", $utf8)
}
# Passwords generated by this installer are hex; reject unexpected input before interpolating SQL.
if ($credentials.APP_PASSWORD -notmatch '^[A-Fa-f0-9]{64}$') { throw 'Formato de contraseña local inesperado.' }
$previousPassword = $env:PGPASSWORD
try {
    $env:PGPASSWORD = $credentials.POSTGRES_PASSWORD
    $psqlArgs = @('-h', '127.0.0.1', '-p', $credentials.POSTGRES_PORT, '-U', $credentials.POSTGRES_USER, '-d', 'postgres', '-X', '-v', 'ON_ERROR_STOP=1', '-w')
    $roleExists = & $psqlPath @psqlArgs -tAc "SELECT count(*) FROM pg_roles WHERE rolname='app_resto'"
    if ($LASTEXITCODE -ne 0) { throw 'No se pudo conectar como administrador local.' }
    if ($roleExists.Trim() -eq '0') {
        "CREATE ROLE app_resto LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD '$($credentials.APP_PASSWORD)';" | & $psqlPath @psqlArgs
        if ($LASTEXITCODE -ne 0) { throw 'No se pudo crear el usuario de aplicación.' }
    }
    $databaseExists = & $psqlPath @psqlArgs -tAc "SELECT count(*) FROM pg_database WHERE datname='app_resto_dev'"
    if ($LASTEXITCODE -ne 0) { throw 'No se pudo comprobar la base local.' }
    if ($databaseExists.Trim() -eq '0') {
        'CREATE DATABASE app_resto_dev OWNER app_resto;' | & $psqlPath @psqlArgs
        if ($LASTEXITCODE -ne 0) { throw 'No se pudo crear la base de desarrollo.' }
    }
    $env:PGPASSWORD = $credentials.APP_PASSWORD
    & $psqlPath -h 127.0.0.1 -p $credentials.POSTGRES_PORT -U app_resto -d app_resto_dev -X -w -tAc 'SELECT 1' | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'No se pudo validar la conexión del usuario de aplicación. Se conserva .env sin cambios.' }
} finally { $env:PGPASSWORD = $previousPassword }

if (Test-Path -LiteralPath $apiEnvPath) {
    $backupPath = Join-Path $projectRoot '.env.api-before-postgres.local'
    if (!(Test-Path -LiteralPath $backupPath)) { Copy-Item -LiteralPath $apiEnvPath -Destination $backupPath }
    $content = [System.IO.File]::ReadAllText($apiEnvPath)
} else { $content = [System.IO.File]::ReadAllText((Join-Path $projectRoot 'apps/api/.env.example')) }

$dbUrl = 'postgresql://app_resto:' + $credentials.APP_PASSWORD + '@127.0.0.1:' + $credentials.POSTGRES_PORT + '/app_resto_dev'
$replacement = 'DATABASE_URL="' + $dbUrl + '"'
if ($content -match '(?m)^DATABASE_URL=') { $content = [regex]::Replace($content, '(?m)^DATABASE_URL=.*$', $replacement) }
else { $content += "`n$replacement`n" }
$secretMatch = [regex]::Match($content, '(?m)^JWT_ACCESS_SECRET=["'']?([^"''\r\n]*)')
if (!$secretMatch.Success -or $secretMatch.Groups[1].Value.Length -lt 32) {
    $bytes = New-Object byte[] 48
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $secret = [BitConverter]::ToString($bytes).Replace('-', '')
    $replacement = 'JWT_ACCESS_SECRET="' + $secret + '"'
    if ($content -match '(?m)^JWT_ACCESS_SECRET=') { $content = [regex]::Replace($content, '(?m)^JWT_ACCESS_SECRET=.*$', $replacement) }
    else { $content += "`n$replacement`n" }
}
[System.IO.File]::WriteAllText($apiEnvPath, $content, $utf8)
Write-Output 'Conexión local configurada en apps/api/.env. Las credenciales no se muestran ni se versionan.'
